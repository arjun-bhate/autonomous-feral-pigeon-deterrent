"""The worked byte-level example in ``protocol/PROTOCOL.md``, produced by code.

A hand-computed example in a document goes stale or was never right. This module
builds one real request and its real reply with the same encoder the simulator
uses and writes them out as Markdown. A test (``tests/unit/test_protocol_doc.py``)
fails if the example pasted into the document differs from what this code
produces today.

Run ``uv run python -m deterrent.protocol.example`` to print the Markdown, then
paste it between the two marker lines in the document.
"""

import struct
from dataclasses import dataclass

from deterrent.protocol.codes import DenyReason
from deterrent.protocol.crc import crc16_ccitt_false
from deterrent.protocol.framing import cobs_encode
from deterrent.protocol.messages import FireRequest, Reply, encode_device_message

BEGIN_MARKER = "<!-- BEGIN WORKED EXAMPLE (generated by src/deterrent/protocol/example.py) -->"
END_MARKER = "<!-- END WORKED EXAMPLE -->"

EXAMPLE_SEQ = 7


@dataclass(frozen=True)
class FrameExample:
    """One message shown at every stage from fields to wire bytes."""

    seq: int
    msg_type: int
    message: object
    payload: bytes
    head: bytes  # type | seq | payload (what the CRC covers)
    crc: int
    raw: bytes  # head | crc16
    wire: bytes  # COBS(raw) | 0x00


def _stages(msg_type: int, seq: int, payload: bytes) -> tuple[bytes, int, bytes, bytes]:
    head = struct.pack("<BH", msg_type, seq) + payload
    crc = crc16_ccitt_false(head)
    raw = head + struct.pack("<H", crc)
    return head, crc, raw, cobs_encode(raw) + b"\x00"


def fire_request_example() -> FrameExample:
    """A FIRE_REQUEST: issued at 1000 ms, valid for 500 ms, aimed at pan 120.00, tilt 40.00."""
    message = FireRequest(
        issued_at_ms=1000, ttl_ms=500, intended_pan=12000, intended_tilt=4000, duration_ms=500
    )
    payload = message.encode_payload()
    head, crc, raw, wire = _stages(int(message.TYPE), EXAMPLE_SEQ, payload)
    return FrameExample(EXAMPLE_SEQ, int(message.TYPE), message, payload, head, crc, raw, wire)


def denial_reply_example() -> FrameExample:
    """The device's reply to the request above when the arm key is off (DENIED KEY_OFF)."""
    reply = Reply.denied(DenyReason.KEY_OFF)
    msg_type, payload = encode_device_message(reply)
    head, crc, raw, wire = _stages(msg_type, EXAMPLE_SEQ, payload)
    return FrameExample(EXAMPLE_SEQ, msg_type, reply, payload, head, crc, raw, wire)


def _hex(data: bytes) -> str:
    return " ".join(f"{byte:02X}" for byte in data)


def render_markdown() -> str:
    """The example as Markdown, exactly as it appears between the document's markers."""
    request = fire_request_example()
    reply = denial_reply_example()
    message = request.message
    assert isinstance(message, FireRequest)
    fields = [
        ("issued_at_ms", "u32", message.issued_at_ms, struct.pack("<I", message.issued_at_ms)),
        ("ttl_ms", "u16", message.ttl_ms, struct.pack("<H", message.ttl_ms)),
        ("intended_pan", "i16", message.intended_pan, struct.pack("<h", message.intended_pan)),
        ("intended_tilt", "i16", message.intended_tilt, struct.pack("<h", message.intended_tilt)),
        ("duration_ms", "u16", message.duration_ms, struct.pack("<H", message.duration_ms)),
    ]
    lines = [
        "The numbers below are produced by `src/deterrent/protocol/example.py` and checked by a "
        "test, so they cannot drift from the encoder. All hex is shown one byte at a time.",
        "",
        f"**Request**: `FIRE_REQUEST` (type {request.msg_type:#04x}), sequence number "
        f"{request.seq}.",
        "",
        "| Field | Type | Value | Bytes (little-endian) |",
        "|-------|------|------:|-----------------------|",
    ]
    lines += [
        f"| {name} | {kind} | {value} | `{_hex(data)}` |" for name, kind, value, data in fields
    ]
    lines += [
        "",
        f"1. Payload (the field bytes in order, {len(request.payload)} bytes): "
        f"`{_hex(request.payload)}`",
        f"2. Type and sequence number, then the payload: `{_hex(request.head)}` "
        f"(type `{request.msg_type:02X}`, sequence `{_hex(struct.pack('<H', request.seq))}`).",
        f"3. CRC-16 over those bytes: `{request.crc:#06x}`, appended low byte first: "
        f"`{_hex(struct.pack('<H', request.crc))}`.",
        f"4. Raw frame ({len(request.raw)} bytes): `{_hex(request.raw)}`",
        f"5. COBS-encoded and followed by the `00` end marker "
        f"({len(request.wire)} bytes on the wire): `{_hex(request.wire)}`",
        "",
        f"**Reply**: the device answers `DENIED`, code {int(DenyReason.KEY_OFF)} "
        f"(`KEY_OFF`), because the arm key is off. The reply type is the request type with bit 7 "
        f"set ({reply.msg_type:#04x}), the sequence number is copied from the request, and the "
        "data is the fault mask (`00 00`).",
        "",
        f"- Payload: `{_hex(reply.payload)}` (result 3 = DENIED, code "
        f"{int(DenyReason.KEY_OFF)}, fault mask 0)",
        f"- CRC-16: `{reply.crc:#06x}`",
        f"- Raw frame: `{_hex(reply.raw)}`",
        f"- On the wire: `{_hex(reply.wire)}`",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(BEGIN_MARKER)
    print(render_markdown(), end="")
    print(END_MARKER)
